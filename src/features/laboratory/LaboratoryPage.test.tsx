import { render, screen, waitFor } from '@testing-library/react'
import userEvent from '@testing-library/user-event'
import { describe, expect, it, vi } from 'vitest'
import { LaboratoryPage } from './LaboratoryPage'

describe('LaboratoryPage', () => {
  it('conserva las seis estrategias y retira únicamente el apartado U/R/M pendiente', () => {
    render(<LaboratoryPage />)
    expect(screen.getAllByRole('article')).toHaveLength(6)
    expect(screen.getAllByText('¿Qué vamos a calcular?')).toHaveLength(6)
    expect(screen.getAllByText('¿Cómo comprobaríamos si ayuda?')).toHaveLength(6)
    expect(screen.getByText(/Cada guía revisada representa un procedimiento/)).toBeInTheDocument()
    expect(screen.getByText('Mejora del trabajo interno')).toBeInTheDocument()
    expect(screen.queryByRole('heading', { name: 'Tipos de sección electoral' })).not.toBeInTheDocument()
    expect(screen.getAllByRole('button', { name: /^Ver detalles:/ })).toHaveLength(6)
    expect(screen.getByText('¿Cómo evaluaríamos esta propuesta?')).toBeInTheDocument()
  })
  it('organiza el escenario y muestra contexto y errores accesibles', async () => {
    const user = userEvent.setup()
    render(<LaboratoryPage />)
    expect(screen.getByRole('group', { name: 'Ponle un nombre a tu escenario' })).toBeInTheDocument()
    expect(screen.getByRole('group', { name: '¿Con qué recursos contarías?' })).toHaveTextContent('cantidades supuestas')
    expect(screen.getByRole('group', { name: '¿Qué quieres realizar?' })).toHaveTextContent('máximo')
    expect(screen.getByText(/Actividad de esta estrategia:/)).toBeInTheDocument()
    expect(screen.getByLabelText('¿Con cuánto dinero contarías? (MXN)')).not.toHaveAttribute('aria-invalid', 'true')
    await user.click(screen.getByRole('button', { name: 'Guardar escenario' }))
    expect(screen.getAllByText('Escribe cuánto dinero tendrías disponible.')).toHaveLength(2)
    expect(screen.getByLabelText('¿Con cuánto dinero contarías? (MXN)')).toHaveAttribute('aria-invalid', 'true')
  })
  it('distingue presupuesto y capacidad en el diagnóstico de resultados', async () => {
    const user = userEvent.setup()
    render(<LaboratoryPage />)
    const fill = async (name: string, value: string) => { const field = screen.getByLabelText(name); await user.clear(field); await user.type(field, value) }
    await fill('¿Con cuánto dinero contarías? (MXN)', '10000')
    await fill('¿Cuánto costaría cada actividad? (MXN)', '200')
    await fill('¿Cuántas actividades quieres realizar?', '60')
    await fill('¿Cuántas actividades podrían realizarse como máximo? (opcional)', '100')
    expect(screen.getByRole('heading', { name: 'El escenario supera el presupuesto disponible' })).toBeInTheDocument()
    expect(screen.getByText(/Se necesitarían \$2,000.00 adicionales/)).toHaveTextContent('50 guías revisadas completas')
    expect(screen.getByRole('button', { name: 'Descargar resultados en PDF' })).toBeEnabled()
    expect(screen.getByRole('button', { name: 'Descargar resultados en PNG' })).toBeEnabled()
    expect(screen.getByText('Presupuesto', { exact: true }).parentElement).toHaveTextContent('Insuficiente')
    expect(screen.getAllByText('Capacidad de trabajo', { exact: true })[0].parentElement).toHaveTextContent('Suficiente')
    expect(screen.getByText(/sólo podrías completar 50/i)).toBeInTheDocument()
    expect(screen.getByText('¿Qué parte del presupuesto usarías?')).toBeInTheDocument()
    expect(screen.getByRole('img', { name: /Actividades frente a lo que podrías completar/i })).toBeInTheDocument()
  })
  it('guía, avanza, retrocede, cierra y reinicia el tour', async () => {
    const user = userEvent.setup()
    render(<LaboratoryPage />)
    await user.click(screen.getByRole('button', { name: '¿Cómo funciona?' }))
    expect(screen.getByRole('dialog')).toHaveTextContent('1. Elige una estrategia')
    await user.click(screen.getByRole('button', { name: 'Siguiente' }))
    expect(screen.getByRole('dialog')).toHaveTextContent('2. Confirma tu elección')
    await user.click(screen.getByRole('button', { name: 'Anterior' }))
    expect(screen.getByRole('dialog')).toHaveTextContent('1. Elige una estrategia')
    await user.click(screen.getByRole('button', { name: 'Salir' }))
    expect(screen.queryByRole('dialog')).not.toBeInTheDocument()
    await user.click(screen.getByRole('button', { name: '¿Cómo funciona?' }))
    expect(screen.getByRole('dialog')).toHaveTextContent('1. Elige una estrategia')
  })
  it('muestra el objetivo destacado y permite salir con Escape', async () => {
    const user = userEvent.setup()
    render(<LaboratoryPage />)
    await user.click(screen.getByRole('button', { name: '¿Cómo funciona?' }))
    expect(screen.getByRole('dialog')).toHaveTextContent('Qué es:')
    expect(screen.getByRole('dialog')).toHaveTextContent('Cómo usarlo:')
    expect(document.querySelector('#lab-catalog .lab-strategy:first-child')).toHaveClass('lab-tour-target')
    await user.keyboard('{Escape}')
    expect(screen.queryByRole('dialog')).not.toBeInTheDocument()
  })
  it('carga un ejemplo ficticio modificable con sus cálculos', async () => {
    const user = userEvent.setup()
    render(<LaboratoryPage />)
    await user.click(screen.getByRole('button', { name: 'Probar con un ejemplo' }))
    expect(screen.getByLabelText('¿Con cuánto dinero contarías? (MXN)')).toHaveValue(10000)
    expect(screen.getByLabelText('¿Cuántas actividades podrían realizarse como máximo? (opcional)')).toHaveValue(40)
    expect(screen.getByText(/Usarías 60% del dinero disponible/i)).toBeInTheDocument()
    await user.clear(screen.getByLabelText('¿Cuántas actividades quieres realizar?'))
    await user.type(screen.getByLabelText('¿Cuántas actividades quieres realizar?'), '20')
    expect(screen.getByText('$4,000.00', { exact: false })).toBeInTheDocument()
  })
  it('guía, avanza, retrocede, cierra y reinicia el tour', async () => {
    const user = userEvent.setup()
    render(<LaboratoryPage />)
    await user.click(screen.getByRole('button', { name: '¿Cómo funciona?' }))
    expect(screen.getByRole('dialog')).toHaveTextContent('1. Elige una estrategia')
    await user.click(screen.getByRole('button', { name: 'Siguiente' }))
    expect(screen.getByRole('dialog')).toHaveTextContent('2. Confirma tu elección')
    await user.click(screen.getByRole('button', { name: 'Anterior' }))
    expect(screen.getByRole('dialog')).toHaveTextContent('1. Elige una estrategia')
    await user.click(screen.getByRole('button', { name: 'Salir' }))
    expect(screen.queryByRole('dialog')).not.toBeInTheDocument()
    await user.click(screen.getByRole('button', { name: '¿Cómo funciona?' }))
    expect(screen.getByRole('dialog')).toHaveTextContent('1. Elige una estrategia')
  })
  it('carga un ejemplo ficticio modificable con sus cálculos', async () => {
    const user = userEvent.setup()
    render(<LaboratoryPage />)
    await user.click(screen.getByRole('button', { name: 'Probar con un ejemplo' }))
    expect(screen.getByLabelText('¿Con cuánto dinero contarías? (MXN)')).toHaveValue(10000)
    expect(screen.getByLabelText('¿Cuántas actividades podrían realizarse como máximo? (opcional)')).toHaveValue(40)
    expect(screen.getByText(/Usarías 60% del dinero disponible/i)).toBeInTheDocument()
    await user.clear(screen.getByLabelText('¿Cuántas actividades quieres realizar?'))
    await user.type(screen.getByLabelText('¿Cuántas actividades quieres realizar?'), '20')
    expect(screen.getByText('$4,000.00', { exact: false })).toBeInTheDocument()
  })
  it('configura, guarda, compara y elimina escenarios', async () => {
    const user = userEvent.setup()
    vi.spyOn(window, 'confirm').mockReturnValue(true)
    render(<LaboratoryPage />)
    const fill = async (name: string, value: string) => { const field = screen.getByLabelText(name); await user.clear(field); await user.type(field, value) }
    await fill('¿Con cuánto dinero contarías? (MXN)', '10000')
    await fill('¿Cuánto costaría cada actividad? (MXN)', '200')
    await fill('¿Cuántas actividades quieres realizar?', '30')
    expect(screen.getByText('$6,000.00', { exact: false })).toBeInTheDocument()
    await user.click(screen.getByRole('button', { name: 'Guardar escenario' }))
    await user.click(screen.getAllByRole('button', { name: /^Elegir esta estrategia$/ })[1])
    await fill('¿Con cuánto dinero contarías? (MXN)', '5000')
    await fill('¿Cuánto costaría cada actividad? (MXN)', '100')
    await fill('¿Cuántas actividades quieres realizar?', '20')
    await user.click(screen.getByRole('button', { name: 'Guardar escenario' }))
    expect(screen.getByLabelText('Gráfica comparativa de costos')).toBeInTheDocument()
    expect(screen.queryByLabelText('Gráfica comparativa de actividades que podrías completar')).not.toBeInTheDocument()
    expect(screen.getByText(/Las estrategias usan medidas distintas/i)).toBeInTheDocument()
    await user.click(screen.getAllByRole('button', { name: /Eliminar Escenario:/ })[0])
    expect(screen.queryByLabelText('Gráfica comparativa de costos')).not.toBeInTheDocument()
    vi.restoreAllMocks()
  })
  it('muestra instrucciones y tarjetas seleccionables para comparar alternativas', async () => {
    const user = userEvent.setup()
    render(<LaboratoryPage />)
    expect(screen.getByText(/Para comparar tus escenarios:/i)).toBeInTheDocument()
    const fill = async (name: string, value: string) => { const field = screen.getByLabelText(name); await user.clear(field); await user.type(field, value) }
    await fill('¿Con cuánto dinero contarías? (MXN)', '10000')
    await fill('¿Cuánto costaría cada actividad? (MXN)', '200')
    await fill('¿Cuántas actividades quieres realizar?', '30')
    await user.click(screen.getByRole('button', { name: 'Guardar escenario' }))
    expect(screen.getByRole('article', { name: /Escenario:/i })).toBeInTheDocument()
    expect(screen.getByText(/Elegido para comparar/i)).toBeInTheDocument()
  })
  it('conserva los datos si se cancela el cambio de estrategia', async () => {
    const user = userEvent.setup()
    vi.spyOn(window, 'confirm').mockReturnValue(false)
    render(<LaboratoryPage />)
    const budget = screen.getByLabelText('¿Con cuánto dinero contarías? (MXN)')
    await user.type(budget, '10000')
    await user.click(screen.getAllByRole('button', { name: /^Elegir esta estrategia$/ })[1])
    expect(budget).toHaveValue(10000)
    expect(screen.getAllByRole('button', { name: 'Estrategia elegida' })[0]).toBeInTheDocument()
    vi.restoreAllMocks()
  })
  it('activa la sección navegada y enfoca su encabezado', async () => {
    Object.defineProperty(window.HTMLElement.prototype, 'scrollIntoView', { configurable: true, value: vi.fn() })
    const user = userEvent.setup()
    render(<LaboratoryPage />)
    await user.click(screen.getByRole('link', { name: '2. Prepara' }))
    expect(screen.getByRole('link', { name: '2. Prepara' })).toHaveAttribute('aria-current', 'step')
    await waitFor(() => expect(screen.getByRole('heading', { name: 'Prepara tu escenario' })).toHaveFocus())
    vi.restoreAllMocks()
  })
})
